// src/modules/quotes/domain/pricing/strategies/kitchen-pricing.strategy.ts
// Implements the pricing strategy for kitchen quotes based on configuration and other factors.

import { Injectable, Logger } from "@nestjs/common";
import { PricingStrategy } from "../pricing-strategy.interface";
import { AnyQuoteRequestDto } from "src/modules/quotes/application/dto/base-quote-request.dto";
import { CreateKitchenQuoteDto } from "src/modules/quotes/application/dto/request/create-kitchen-quote.dto";
import { CalculatorType } from "../../enums/calculator-type.enum";
import { ConfigService } from "@nestjs/config";

@Injectable()
export class KitchenPricingStrategy implements PricingStrategy {
  private readonly logger = new Logger(KitchenPricingStrategy.name);

  readonly pricingVersion: string;

  // Base rate per running foot by package tier
  private readonly PACKAGE_RATES: Record<string, number> = {
    ESSENTIAL: 1800,
    PREMIUM: 2500,
    LUXURY: 3500,
  };

  // Default fallback rate per running foot if package is custom/unrecognized
  private readonly DEFAULT_RATE = 2200;

  constructor(private readonly config: ConfigService) {
    // Fixed config key to target kitchen pricing version instead of full-home
    this.pricingVersion =
      this.config.get<string>("KITCHEN_PRICING_VERSION") || "kitchen-v1";
  }

  supports(type: CalculatorType): boolean {
    return type === CalculatorType.KITCHEN;
  }

  calculateEstimate(quoteRequest: AnyQuoteRequestDto): number {
    const dto = quoteRequest as CreateKitchenQuoteDto;
    const { package: packageName, builtupArea } = dto.configuration;

    const runningFeet = this.extractTotalRunningFeet(builtupArea);
    const ratePerFoot = this.PACKAGE_RATES[packageName] ?? this.DEFAULT_RATE;

    const basePrice = runningFeet * ratePerFoot;

    // Apply standard GST/Tax or rounding logic if applicable (e.g., round to nearest hundred)
    const finalEstimate = Math.round(basePrice);

    this.logger.debug(
      `Calculated Kitchen Estimate: ${runningFeet} ft @ ₹${ratePerFoot}/ft = ₹${finalEstimate}`,
    );

    return finalEstimate;
  }

  getPricingSnapshot(): Record<string, unknown> {
    return {
      strategyVersion: this.pricingVersion,
      packageRates: structuredClone(this.PACKAGE_RATES),
      defaultRate: this.DEFAULT_RATE,
      calculatedAt: new Date().toISOString(),
    };
  }

  /**
   * Safe helper to extract total running feet from string representations.
   * Handles formats like "A: 8ft, B: 10ft (Total: 18ft)" or raw numbers embedded in text.
   */
  private extractTotalRunningFeet(builtupArea: string | number): number {
    if (typeof builtupArea === "number") {
      return builtupArea > 0 ? builtupArea : 0;
    }

    if (!builtupArea || typeof builtupArea !== "string") {
      return 0;
    }

    // 1. Try matching explicit "(Total: XXft)" pattern generated by UI
    const totalMatch = builtupArea.match(/\(Total:\s*(\d+(\.\d+)?)\s*ft\)/i);
    if (totalMatch && totalMatch[1]) {
      return parseFloat(totalMatch[1]);
    }

    // 2. Fallback: Parse individual wall segments (e.g., "A: 8ft", "B: 10ft") and sum them up
    const matches = [...builtupArea.matchAll(/:\s*(\d+(\.\d+)?)\s*ft/gi)];
    if (matches.length > 0) {
      return matches.reduce((sum, match) => sum + parseFloat(match[1]), 0);
    }

    // 3. Fallback: Extract first isolated number found in string
    const fallbackMatch = builtupArea.match(/(\d+(\.\d+)?)/);
    return fallbackMatch ? parseFloat(fallbackMatch[1]) : 0;
  }
}
